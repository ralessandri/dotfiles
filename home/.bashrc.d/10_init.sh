# Read the current DMS Material colors generated by Matugen.
DMS_COLORS_FILE="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0/dank-colors.css"

__dms_color() {
  local color_name="$1"
  local fallback="$2"
  local color

  color="$(
    sed -n \
      "s/^@define-color ${color_name} #\\([[:xdigit:]]\\{6\\}\\);/\\1/p" \
      "$DMS_COLORS_FILE" 2>/dev/null |
      head -n 1
  )"

  printf '%s' "${color:-$fallback}"
}

FZF_FOREGROUND="$(__dms_color window_fg_color dfe3e7)"
FZF_PRIMARY="$(__dms_color accent_bg_color 90cef4)"
FZF_ON_PRIMARY="$(__dms_color accent_fg_color 00344a)"

export FZF_DEFAULT_OPTS="${FZF_DEFAULT_OPTS:-} \
  --highlight-line \
