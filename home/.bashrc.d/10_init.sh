  --ansi \
  --border=none \
  --color=bg+:#${FZF_PRIMARY} \
  --color=bg:-1 \
  --color=border:#${FZF_PRIMARY} \
  --color=fg:#${FZF_FOREGROUND} \
  --color=fg+:#${FZF_ON_PRIMARY} \
  --color=gutter:-1 \
  --color=header:#${FZF_FOREGROUND} \
  --color=hl+:#${FZF_ON_PRIMARY} \
  --color=hl:#${FZF_PRIMARY} \
  --color=info:#${FZF_PRIMARY} \
  --color=marker:#${FZF_PRIMARY} \
  --color=pointer:#${FZF_PRIMARY} \
  --color=preview-bg:-1 \
